def render(skel):
    """skeleton rows -> 16x8 colour indices (1 top / 2 bottom skeleton, 3 outline)."""
    sk = [[skel.get(y, '........')[x] == '#' for x in range(8)] for y in range(16)]
    out = [[0] * 8 for _ in range(16)]
    for y in range(16):
        for x in range(8):
            if sk[y][x]:
                out[y][x] = 1 if y < 8 else 2
            elif any(0 <= y + dy < 16 and 0 <= x + dx < 8 and sk[y + dy][x + dx]
                     for dy in (-1, 0, 1) for dx in (-1, 0, 1)):
                out[y][x] = 3
    return out


def encode(pix):
    b = bytearray()
    for half in range(2):
        for y in range(8):
            row = pix[half * 8 + y]
            p0 = p1 = 0
            for x in range(8):
                p0 |= (row[x] & 1) << (7 - x); p1 |= (row[x] >> 1) << (7 - x)
            b += bytes([p0, p1])
    return bytes(b)


def decode(data):
    pix = []
    for half in range(2):
        for y in range(8):
            p0, p1 = data[half * 16 + 2 * y], data[half * 16 + 2 * y + 1]
            pix.append([((p0 >> (7 - x)) & 1) | (((p1 >> (7 - x)) & 1) << 1) for x in range(8)])
    return pix


def patch(rom):
    for ch, skel in LOWER.items():
        code = ord(ch) - 0x1E
        rom[FONT + code * 32:FONT + code * 32 + 32] = encode(render(skel))


def skeleton_of(pix):
    return {y: ''.join('#' if v in (1, 2) else '.' for v in row) for y, row in enumerate(pix) if any(v in (1, 2) for v in row)}


