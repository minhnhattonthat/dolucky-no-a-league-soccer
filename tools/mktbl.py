"""Generate tbl/jp.tbl and tbl/en.tbl from the font layout ($91:8000, 8x16, one code per glyph).

    python -X utf8 tools/mktbl.py

Codes 02-60: ASCII minus 0x1E (space=02, A=23, a=43 .. z=5C; lowercase slots are blank in the original font and
filled by our font patch). 00 = end, 01 = new line. Kana: 61-D6. Dakuten/handakuten are separate codes (67/68)
after the kana; jp.tbl folds them into two-byte entries so `jp` fields read naturally.
"""
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
KATA = 'アイウエオカキクケコサシスセソタチツテトナニヌネノハヒフヘホマミムメモヤユヨラリルレロワン'
HIRA = 'あいうえおかきくけこさしすせそたちつてとなにぬねのはひふへほまみむめもやゆよらりるれろわん'
SYM = {0x60: '‾', 0x61: '。', 0x62: '「', 0x63: '」', 0x64: '、', 0x65: '・', 0x66: 'ー', 0x67: '゛', 0x68: '゜',
       0x69: 'ヲ', 0xA0: 'を'}
for i, c in enumerate('ァィゥェォッャュョ'):
    SYM[0x6A + i] = c
for i, c in enumerate('ぁぃぅぇぉっゃゅょ'):
    SYM[0xA1 + i] = c
DAK = dict(zip('かきくけこさしすせそたちつてとはひふへほカキクケコサシスセソタチツテトハヒフヘホウ',
               'がぎぐげござじずぜぞだぢづでどばびぶべぼガギグゲゴザジズゼゾダヂヅデドバビブベボヴ'))
HAN = dict(zip('はひふへほハヒフヘホ', 'ぱぴぷぺぽパピプペポ'))


def ascii_rows(lower):
    rows = ['00={end}', '01={n}', '02=\\s']
    for c in range(0x21, 0x7F):
        ch = chr(c)
        if 'a' <= ch <= 'z' and not lower:
            continue
        rows.append('%02X=%s' % (c - 0x1E, ch))
    return rows


def kana():
    single = dict(SYM)
    for i, c in enumerate(KATA):
        single[0x73 + i] = c
    for i, c in enumerate(HIRA):
        single[0xAA + i] = c
    rows = ['%02X=%s' % (k, v) for k, v in sorted(single.items())]
    for k, v in sorted(single.items()):
        if v in DAK:
            rows.append('%02X67=%s' % (k, DAK[v]))
        if v in HAN:
            rows.append('%02X68=%s' % (k, HAN[v]))
    return rows


def main():
    os.makedirs(os.path.join(ROOT, 'tbl'), exist_ok=True)
    hdr = ['# generated by tools/mktbl.py; do not edit']
    with open(os.path.join(ROOT, 'tbl', 'jp.tbl'), 'w', encoding='utf-8', newline='\n') as f:
        f.write('\n'.join(hdr + ascii_rows(False) + kana()) + '\n')
    with open(os.path.join(ROOT, 'tbl', 'en.tbl'), 'w', encoding='utf-8', newline='\n') as f:
        f.write('\n'.join(hdr + ascii_rows(True)) + '\n')


if __name__ == '__main__':
    main()
